static int g_initialized = 0;

/* Initialize Lean's runtime + the Tgrad module. Must be called once
 * before any other tgrad_* function. Returns 0 on success, -1 on init
 * error. Subsequent calls are no-ops. */
int tgrad_init(void) {
    if (g_initialized) return 0;
    /* Mirror Lake's executable main() wrapper. lean_initialize() sets
     * up the GC / object pool / IO runtime; init_task_manager is
     * required for blocking IO ops (readFile, etc.) to schedule
     * correctly. Skip either of these and IO operations crash inside
     * lean_dec_ref_cold on the IO world's task state. */
    lean_initialize();
    lean_set_panic_messages(false);
    lean_object* res = initialize_tgrad_Tgrad(1);
    lean_set_panic_messages(true);
    if (lean_io_result_is_error(res)) {
        lean_dec_ref(res);
        return -1;
    }
    lean_dec_ref(res);
    lean_io_mark_end_initialization();
    lean_init_task_manager();
    g_initialized = 1;
    return 0;
}

/* Refcount exposers — Lean's lean_inc_ref / lean_dec_ref are static
 * inline in lean.h, so Python's ctypes can't reach them. Expose as real
 * symbols for Python's `weakref.finalize` lifecycle. (For the matmul
 * surface we don't currently hand Python opaque Lean structures, but
 * keeping these here makes the dylib spec-complete per §G6.b.) */
void tgrad_handle_inc(void* h) {
    if (h) lean_inc_ref((lean_object*)h);
}

void tgrad_handle_dec(void* h) {
    if (h) lean_dec_ref((lean_object*)h);
}

