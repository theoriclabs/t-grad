/* int tgrad_tensor_write_bytes(uint64_t buf_ptr, const uint8_t* src, size_t n_bytes)
 * Copies `n_bytes` from `src` into the buffer at offset 0.
 * Returns 0 on success, negative on error. */
int tgrad_tensor_write_bytes(uint64_t buf_ptr, const uint8_t* src, size_t n_bytes) {
    if (!src) return -1;
    /* Allocate a Lean ByteArray of `n_bytes`; copy into its data;
     * pass to the @[export] entry which copies again to MTLBuffer
     * contents. (Two host-side copies; acceptable for L6.b — matches
     * the §G_L5_b path.) */
    lean_object* arr = lean_alloc_sarray(1, n_bytes, n_bytes);
    if (!arr) return -2;
    memcpy(lean_sarray_cptr(arr), src, n_bytes);
    lean_object* result = tgrad_tensor_write_bytes_lean(buf_ptr, arr);
    int rc = lean_io_result_is_error(result) ? -3 : 0;
    lean_dec_ref(result);
    return rc;
}

/* int tgrad_tensor_read_bytes(uint64_t buf_ptr, uint8_t* dst, size_t n_bytes)
 * Copies `n_bytes` from the buffer's contents into `dst`.
 * Returns 0 on success, negative on error. */
int tgrad_tensor_read_bytes(uint64_t buf_ptr, uint8_t* dst, size_t n_bytes) {
    if (n_bytes == 0) return 0;
    if (!buf_ptr) return -1;
    if (!dst) return -1;
    lean_object* result = tgrad_tensor_read_bytes_lean(buf_ptr, n_bytes);
    if (lean_io_result_is_error(result)) {
        lean_dec_ref(result);
        return -2;
    }
    lean_object* arr = lean_io_result_get_value(result);   /* borrowed */
    size_t actual = lean_sarray_size(arr);
    if (actual < n_bytes) {
        lean_dec_ref(result);
        return -3;
    }
    memcpy(dst, lean_sarray_cptr(arr), n_bytes);
    lean_dec_ref(result);
    return 0;
}

